/// ثابت بيئة البناء للتحكم في تضمين وتفعيل لوحة التحكم وصلاحيات الإدارة وقت الترجمة.
///
/// يوفر ثابتاً عاماً وقت الترجمة (Compile-time constant) لعزل بيئة المستخدم العادي
/// عن بيئة الإدارة والتحكم (Admin) بأسلوب الشجرة المهزوزة (Tree Shaking).
///
/// عند بناء نسخة المدير:
/// `flutter build apk --dart-define=IS_ADMIN=true`
///
/// عند بناء نسخة المستخدمين العامة:
/// `flutter build apk` (تكون تلقائياً `IS_ADMIN=false`)
///
/// عندما تكون `false`:
/// - يتم استبعاد وحذف شاشات الإدارة بالكامل من حزمة التطبيق (Tree Shaking).
/// - يتم تعطيل كافة عمليات التعديل والحذف والإضافة السحابية في مزود البيانات.
/// - يظهر التطبيق بواجهة المستخدمين العامة النقية دون أي أثر للمدير.
